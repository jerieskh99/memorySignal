#!/usr/bin/env python3
"""Console bridge -- localhost server that lets the Capture Console UI plan,
preflight, launch, monitor, and stop captures ON THE SERVER it runs on.

Runs where run_files_controlled.py runs (the QEMU host). The browser reaches it
over an SSH tunnel:

    server$  python3 ui/console_bridge.py --port 8000
    laptop$  ssh -L 8000:localhost:8000 user@server
    laptop   open http://localhost:8000/?token=<printed-on-server-stdout>

SECURITY (see ui/README.md):
  * Binds 127.0.0.1 ONLY -- never network-exposed; reachable solely via the
    user's own SSH tunnel.
  * Jupyter-style token: printed to stdout on startup, required in the GET /
    URL (`/?token=...`) and in the X-Console-Token header on every API call.
    On a shared host any co-resident process can hit 127.0.0.1:port, so the
    token (which only the operator's terminal shows) is what gates access --
    GET / without it returns 403 and never leaks the token.
  * Trusted re-derivation: the UI sends structured intent (config + per-cell
    curation), NEVER raw commands. Guest commands are regenerated by
    subset_run.py from full_campaign_steps.txt, so nothing arbitrary reaches
    the guest. The launch line is built by subset_run.py's own env functions,
    so only known env keys can appear; UI-supplied host values (ssh target/key,
    zstd dir) are shlex-quoted by subset_run before they enter the line.
  * Namespaced screens: mem_console_<label>. /status and /stop only ever touch
    mem_console_* sessions.
  * The SSH key never touches the bridge process -- run_files_controlled.py uses
    it on the server exactly as today.

stdlib only.
"""
