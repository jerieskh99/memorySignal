def _valid_label(label: str) -> bool:
    return isinstance(label, str) and bool(LABEL_RE.match(label))


def _write_tmp(text: str, suffix: str) -> Path:
    fd, name = tempfile.mkstemp(suffix=suffix, prefix="console_", dir=str(RUNS / ".staging"))
    p = Path(name)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    return p


def _run(argv: list[str], cwd: Path, env: dict | None = None, timeout: int = 120):
    """subprocess.run wrapper returning (rc, stdout, stderr)."""
    r = subprocess.run(argv, cwd=str(cwd), env=env, capture_output=True,
                       text=True, timeout=timeout)
    return r.returncode, r.stdout, r.stderr


def _subset_run(config: dict, seed: int, *, print_cells: bool = False,
                curation: list | None = None, out: Path | None = None,
                runs_dir: Path | None = None, ssh_target: str | None = None,
                ssh_key: str | None = None, zstd_dir: str | None = None):
    """Invoke subset_run.py as a subprocess. Returns (rc, stdout, stderr).

    Config/curation are passed as temp JSON files. subset_run.py is the single
    trusted generator: it validates, re-derives the guest commands, and (for the
    write path) composes the launch line from known env functions only.
    """
    cfg_path = _write_tmp(json.dumps(config), ".config.json")
    argv = [sys.executable, str(SUBSET_RUN), "--config", str(cfg_path), "--seed", str(seed)]
    cur_path = None
    if print_cells:
        argv.append("--print-cells")
    else:
        argv += ["--out", str(out), "--runs-dir", str(runs_dir)]
        if ssh_target:
            argv += ["--ssh-target", ssh_target]
        if ssh_key:
            argv += ["--ssh-key", ssh_key]
        if zstd_dir:
            argv += ["--zstd-dir", zstd_dir]
        if curation is not None:
            cur_path = _write_tmp(json.dumps(curation), ".curation.json")
            argv += ["--curation", str(cur_path)]
    try:
        return _run(argv, cwd=CAMPAIGN, timeout=120)
    finally:
        cfg_path.unlink(missing_ok=True)
        if cur_path:
            cur_path.unlink(missing_ok=True)


def _screens() -> list[str]:
    """Active screen sessions named mem_console_*. `screen -ls` exits 1 when
    sessions exist, so ignore rc and parse stdout."""
    try:
        r = subprocess.run(["screen", "-ls"], capture_output=True, text=True, timeout=10)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return []
    out = []
    for line in r.stdout.splitlines():
        m = re.search(r"\b(\d+\." + re.escape(SCREEN_PREFIX) + r"[A-Za-z0-9_-]+)", line)
        if m:
            out.append(m.group(1))
    return out


