# --------------------------------------------------------------------------- #
# HTTP handler
# --------------------------------------------------------------------------- #
class Handler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass  # quiet; we print our own concise line below

    def _send(self, code: int, obj, content_type="application/json"):
        if content_type == "application/json":
            payload = json.dumps(obj).encode()
        else:
            payload = obj if isinstance(obj, bytes) else obj.encode()
        self.send_response(code)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(payload)))
        # localhost + tunnel only; no CORS (same-origin from the served page).
        self.end_headers()
        self.wfile.write(payload)

    def _token_ok_header(self) -> bool:
        return secrets.compare_digest(self.headers.get("X-Console-Token", ""), TOKEN)

    def do_GET(self):
        u = urlparse(self.path)
        if u.path == "/" or u.path == "/index.html":
            q = parse_qs(u.query)
            tok = (q.get("token") or [""])[0]
            if not secrets.compare_digest(tok, TOKEN):
                self._send(403, "Forbidden: open the URL printed on the server, "
                                "including ?token=... (see console_bridge stdout).",
                           content_type="text/plain")
                return
            self._serve_app()
            return
        if u.path in ROUTES_GET:
            if not self._token_ok_header():
                self._send(403, {"error": "missing/invalid X-Console-Token"})
                return
            try:
                code, obj = ROUTES_GET[u.path](parse_qs(u.query))
            except Exception as e:  # noqa: BLE001 -- surface as JSON, never 500-crash the thread
                code, obj = 500, {"error": type(e).__name__, "detail": str(e)}
            self._send(code, obj)
            return
        self._send(404, {"error": "not found"})

    def do_POST(self):
        u = urlparse(self.path)
        if u.path not in ROUTES_POST:
            self._send(404, {"error": "not found"})
            return
        if not self._token_ok_header():
            self._send(403, {"error": "missing/invalid X-Console-Token"})
            return
        try:
            length = int(self.headers.get("Content-Length", "0"))
            body = json.loads(self.rfile.read(length) or "{}")
        except (ValueError, json.JSONDecodeError):
            self._send(400, {"error": "body must be JSON"})
            return
        try:
            code, obj = ROUTES_POST[u.path](body)
        except Exception as e:  # noqa: BLE001
            code, obj = 500, {"error": type(e).__name__, "detail": str(e)}
        self._send(code, obj)

    def _serve_app(self):
        if not SERVED_HTML.exists():
            self._send(500, f"served UI not built -- run: python3 ui/build_console.py --served\n"
                            f"(expected {SERVED_HTML})", content_type="text/plain")
            return
        html = SERVED_HTML.read_text()
        # Inject the bridge base + token so the page's API client can call back.
        inject = (f'<script>window.__BRIDGE__={{base:"",token:{json.dumps(TOKEN)}}};</script>')
        html = html.replace("<!--@@BRIDGE_INJECT@@-->", inject)
        self._send(200, html, content_type="text/html; charset=utf-8")


def main() -> int:
    global TOKEN, PORT
    ap = argparse.ArgumentParser(description="Capture Console bridge (localhost only)")
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--token", type=str, default=None,
                    help="fixed token (default: a fresh random one each start)")
    a = ap.parse_args()

    (RUNS / ".staging").mkdir(parents=True, exist_ok=True)
    TOKEN = a.token or secrets.token_urlsafe(24)
    PORT = a.port

    if not SUBSET_RUN.exists():
        sys.exit(f"subset_run.py not found at {SUBSET_RUN}")
    if not SERVED_HTML.exists():
        print(f"[bridge] WARNING: served UI missing -- run: python3 ui/build_console.py --served")

    server = ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    url = f"http://localhost:{PORT}/?token={TOKEN}"
    print("=" * 70)
    print("  Capture Console bridge -- LOCALHOST ONLY (127.0.0.1)")
    print(f"  From your laptop:  ssh -L {PORT}:localhost:{PORT} <user>@<this-server>")
    print(f"  Then open:         {url}")
    print("  Keep this token private; anyone with it can launch captures as you.")
    print("=" * 70)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n[bridge] shutting down")
        server.shutdown()
    return 0


